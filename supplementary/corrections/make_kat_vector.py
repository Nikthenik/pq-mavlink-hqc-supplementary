#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Genera ap_kem_katvec.h con el primer vector publicado del KAT de PQClean para HQC-128
(secret key, ciphertext y shared secret esperado). Es material de prueba publico, no una clave
real: sirve para que el firmware compruebe al arrancar que su KEM descapsula como la referencia.
Uso: python generar_vector.py [kat_up.rsp] [salida.h]"""
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")
RSP = sys.argv[1] if len(sys.argv) > 1 else r"D:\Tesis\_compilar_rev\hqc_equiv\kat_up.rsp"
OUT = sys.argv[2] if len(sys.argv) > 2 else r"D:\Tesis\_compilar_rev\parche_fw\ap_kem_katvec.h"

campos = {}
for lin in open(RSP, encoding="utf-8", errors="replace"):
    m = re.match(r"(\w+) = (.*)", lin.strip())
    if m and m.group(1) not in campos:
        campos[m.group(1)] = m.group(2)
for c in ("sk", "ct", "ss"):
    if c not in campos:
        sys.exit("ABORTA: falta el campo %s en %s" % (c, RSP))


def arreglo(nombre, hexa):
    b = bytes.fromhex(hexa)
    lin = ["static const uint8_t %s[%d] = {" % (nombre, len(b))]
    for i in range(0, len(b), 12):
        lin.append("    " + " ".join("0x%02x," % x for x in b[i:i + 12]))
    lin.append("};")
    return "\n".join(lin), len(b)


sk, nsk = arreglo("AP_KEM_KAT_SK", campos["sk"])
ct, nct = arreglo("AP_KEM_KAT_CT", campos["ct"])
ss, nss = arreglo("AP_KEM_KAT_SS", campos["ss"])
cab = """#pragma once
/*
 * First published known-answer vector of PQClean's HQC-128 test suite (count = 0).
 * Public test data, not key material of any deployment: the self-test decapsulates
 * AP_KEM_KAT_CT with AP_KEM_KAT_SK and requires AP_KEM_KAT_SS, which detects a KEM whose
 * arithmetic does not compute HQC-128 (finding F6).
 * Generated by 09_revision/.../generar_vector.py from the reference tree's .rsp file.
 */
#include <stdint.h>

"""
open(OUT, "w", encoding="utf-8", newline="\n").write(cab + sk + "\n\n" + ct + "\n\n" + ss + "\n")
print("escrito %s (sk %d B, ct %d B, ss %d B)" % (os.path.basename(OUT), nsk, nct, nss))
